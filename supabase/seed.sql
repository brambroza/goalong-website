## 1. ความปลอดภัย

โค้ดที่ AI สร้างมักทำงานได้ตามที่ขอ แต่ไม่ได้คิดเผื่อคนที่ตั้งใจเข้ามาโจมตี จุดที่พบบ่อยคือ

- **รหัสผ่านหรือ API key ฝังอยู่ในโค้ดฝั่งหน้าเว็บ** ใครเปิดดูซอร์สก็เห็น
- **ฐานข้อมูลไม่ได้จำกัดสิทธิ์** ผู้ใช้คนหนึ่งเห็นหรือแก้ข้อมูลของคนอื่นได้ เช่น ตั้งค่า Row Level Security ใน Supabase ไม่ครบ
- **ไม่ตรวจข้อมูลที่ผู้ใช้ส่งเข้ามา** เปิดช่องให้ SQL injection หรือฝังสคริปต์
- **ไม่มีการจำกัดจำนวนครั้ง** ทำให้ถูกยิงจนค่าใช้จ่าย API พุ่ง

